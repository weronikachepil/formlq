/** Easier (3 × 3) cases first, then 4 × 4. */
export const LOGIC_CASES: LogicCase[] = [...CASES].sort((a, b) => a.who.length - b.who.length);

function perms(n: number): number[][] {
  if (n === 1) return [[0]];
  return perms(n - 1).flatMap((p) => Array.from({ length: n }, (_, k) => [...p.slice(0, k), n - 1, ...p.slice(k)]));
}

/** How many item/place assignments satisfy all clues of a case (must be 1, and the solution). */
export function countSolutions(c: LogicCase): { count: number; matches: boolean } {
  let count = 0, matches = false;
  for (const i of perms(c.who.length)) for (const p of perms(c.who.length)) {
    if (c.clues.every((cl) => cl.check(i, p))) {
      count++;
      if (i.join() === c.item.join() && p.join() === c.place.join()) matches = true;
    }
  }
  return { count, matches };
}
